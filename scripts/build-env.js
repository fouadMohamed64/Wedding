/* Generates public/js/env.js from environment variables (Vercel build step).
   Locally it also reads a .env file in the project root if present.
   Only the PUBLIC anon key is ever written. Never put the service-role key here. */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const envFile = path.join(root, ".env");

if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}

const url = process.env.SUPABASE_URL || "";
const anon = process.env.SUPABASE_ANON_KEY || "";

if (/service_role/i.test(anon) || anon.split(".").length === 3 && /"role"\s*:\s*"service_role"/.test(Buffer.from(anon.split(".")[1], "base64").toString("utf8"))) {
  console.error("✖ SUPABASE_ANON_KEY looks like a service_role key. Use the anon/public key instead.");
  process.exit(1);
}

const target = path.join(root, "public", "js", "env.js");

if (!url || !anon) {
  console.warn("⚠ SUPABASE_URL / SUPABASE_ANON_KEY not set — keeping existing public/js/env.js (wishes will be disabled).");
  process.exit(0);
}

const out = `/* Auto-generated by scripts/build-env.js — do not edit. */
window.ENV = ${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: anon }, null, 2)};
`;
fs.writeFileSync(target, out);
console.log("✔ public/js/env.js generated from environment variables.");
